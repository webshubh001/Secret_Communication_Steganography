"""
training/train_lstm.py — Train the LSTM sequence encoder
=========================================================

This script trains a small Bidirectional LSTM to encode byte sequences.
It is an autoencoder at the sequence level:

    Input bytes (padded to seq_len) → LSTM encoder → features → LSTM decoder → reconstructed bytes

We train on randomly generated byte sequences (self-supervised):
    • Input:  random byte windows (SEQUENCE_LENGTH floats in [0,1])
    • Target: same window (reconstruction task)

The trained ENCODER half is what LSTMProcessor uses at runtime.

Usage
-----
    python training/train_lstm.py

Output
------
    models/lstm_model.keras   ← the encoder model used at runtime

Requirements
------------
    tensorflow>=2.13
"""

import os
import sys
import numpy as np

# ── Add project root to path ──────────────────────────────────────────────────
PROJECT_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, PROJECT_ROOT)

SEQUENCE_LENGTH = 64    # must match modules/lstm_processor.py
FEATURE_DIM     = 8     # output feature vector size
HIDDEN_UNITS    = 32    # LSTM hidden state size

MODEL_SAVE_PATH = os.path.join(PROJECT_ROOT, 'models', 'lstm_model.keras')
EPOCHS          = 30
BATCH_SIZE      = 256
NUM_SAMPLES     = 50_000   # synthetic training samples


def build_encoder_model(seq_len: int, hidden: int, feat_dim: int):
    """
    Build and return the LSTM encoder model.

    Architecture:
        Input (seq_len, 1)
          → Bidirectional LSTM(hidden) [processes sequence in both directions]
              - forward LSTM:  reads left → right
              - backward LSTM: reads right → left
              - concatenates both hidden states → 2*hidden dimensional vector
          → Dense(feat_dim, relu)  [compact feature vector]

    The Bidirectional wrapper captures both past and future context within
    the byte window, improving sequence representation quality.
    """
    import tensorflow as tf
    from tensorflow import keras

    inputs = keras.Input(shape=(seq_len, 1), name='byte_sequence')

    # ── Hidden state / Cell state ──────────────────────────────────────────────
    # The LSTM maintains:
    #   h_t (hidden state)  — short-term memory, output at each step
    #   c_t (cell state)    — long-term memory, preserved across steps
    #
    # Gates control information flow (computed internally by Keras):
    #   Forget gate:  decides what to erase from c_{t-1}
    #   Input gate:   decides what new information to store
    #   Output gate:  decides what part of c_t to expose as h_t
    # ──────────────────────────────────────────────────────────────────────────
    x = keras.layers.Bidirectional(
        keras.layers.LSTM(
            hidden,
            return_sequences=False,   # we want one vector per window, not per step
            name='lstm_core'
        ),
        name='bidirectional_lstm'
    )(inputs)

    # Dense projection to compact feature space
    features = keras.layers.Dense(feat_dim, activation='relu', name='features')(x)

    encoder = keras.Model(inputs=inputs, outputs=features, name='lstm_encoder')
    return encoder


def build_full_autoencoder(seq_len: int, hidden: int, feat_dim: int):
    """
    Build encoder + decoder for self-supervised training.
    Only the encoder is saved after training.
    """
    import tensorflow as tf
    from tensorflow import keras

    encoder = build_encoder_model(seq_len, hidden, feat_dim)

    # ── Decoder ────────────────────────────────────────────────────────────────
    feat_input = keras.Input(shape=(feat_dim,))
    # Repeat the feature vector seq_len times so the LSTM decoder has a sequence
    x = keras.layers.RepeatVector(seq_len)(feat_input)
    x = keras.layers.LSTM(hidden, return_sequences=True, name='lstm_decoder')(x)
    x = keras.layers.TimeDistributed(keras.layers.Dense(1, activation='sigmoid'),
                                     name='output')(x)
    decoder = keras.Model(inputs=feat_input, outputs=x, name='lstm_decoder')

    # ── Full autoencoder ───────────────────────────────────────────────────────
    inputs = keras.Input(shape=(seq_len, 1))
    encoded = encoder(inputs)
    reconstructed = decoder(encoded)
    autoencoder = keras.Model(inputs=inputs, outputs=reconstructed,
                              name='lstm_autoencoder')

    autoencoder.compile(
        optimizer='adam',
        loss='mse',
        metrics=['mae']
    )
    return autoencoder, encoder


def generate_training_data(num_samples: int, seq_len: int):
    """
    Generate synthetic byte sequence training data.
    Sequences are random float arrays in [0, 1] (simulating normalised bytes).
    """
    print(f"Generating {num_samples} synthetic byte sequences of length {seq_len}...")
    X = np.random.rand(num_samples, seq_len, 1).astype(np.float32)
    return X, X   # autoencoder: input == target


def main():
    try:
        import tensorflow as tf
        print(f"TensorFlow version: {tf.__version__}")
    except ImportError:
        print("ERROR: TensorFlow is not installed.")
        print("Install with:  pip install tensorflow")
        sys.exit(1)

    print("\n=== LSTM Sequence Encoder Training ===")
    print(f"  Sequence length : {SEQUENCE_LENGTH}")
    print(f"  LSTM hidden dim : {HIDDEN_UNITS}")
    print(f"  Feature dim     : {FEATURE_DIM}")
    print(f"  Epochs          : {EPOCHS}")
    print(f"  Samples         : {NUM_SAMPLES}")

    # Build model
    autoencoder, encoder = build_full_autoencoder(
        SEQUENCE_LENGTH, HIDDEN_UNITS, FEATURE_DIM
    )
    autoencoder.summary()
    encoder.summary()

    # Generate data
    X_train, y_train = generate_training_data(NUM_SAMPLES, SEQUENCE_LENGTH)

    # Train
    print("\nTraining...")
    history = autoencoder.fit(
        X_train, y_train,
        epochs=EPOCHS,
        batch_size=BATCH_SIZE,
        validation_split=0.1,
        verbose=1,
    )

    # Save ONLY the encoder (that is what LSTMProcessor loads)
    os.makedirs(os.path.dirname(MODEL_SAVE_PATH), exist_ok=True)
    encoder.save(MODEL_SAVE_PATH)
    print(f"\nEncoder saved to: {MODEL_SAVE_PATH}")

    final_loss = history.history['val_loss'][-1]
    print(f"Final validation loss: {final_loss:.6f}")
    print("\nDone. Run the Flask app — LSTM processor will load automatically.")


if __name__ == '__main__':
    main()
